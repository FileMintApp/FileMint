import Foundation

/// Pure name descriptors. Native parent/item identity and authority belong to P2.
public struct BatchRenameSource: Equatable, Sendable {
    public let id: UUID
    public let originalName: String
    public let kind: RenameItemKind

    public init(id: UUID, originalName: String, kind: RenameItemKind) {
        self.id = id; self.originalName = originalName; self.kind = kind
    }

    public static func == (lhs: Self, rhs: Self) -> Bool {
        lhs.id == rhs.id && lhs.kind == rhs.kind && lhs.originalName.utf8.elementsEqual(rhs.originalName.utf8)
    }
}

public enum BatchRenamePlanningError: Error, Equatable, Sendable {
    case invalidSelectionCount
    case duplicateSourceID
    case duplicateOriginalName
    case invalidOriginalName(rowID: UUID, reason: RenameNameError)
    case nameListTooLarge
    case invalidNameListBinding
    case nameListLineCount(expected: Int, actual: Int)
    case nameListOrderNeedsConfirmation
    case staleTargetSnapshot
    case invalidTargetObservation
    case unknownCaseSensitivity
    case previewNotReady
    case noChanges
}

/// Capture once, then reuse the original parts for every revision.
public struct BatchRenameBatch: Equatable, Sendable {
    public let id: UUID
    public let sources: [BatchRenameSource]
    let parts: [RenameNameParts]

    public init(id: UUID, sources: [BatchRenameSource]) throws {
        guard (2...1_000).contains(sources.count) else { throw BatchRenamePlanningError.invalidSelectionCount }
        guard Set(sources.map(\.id)).count == sources.count else { throw BatchRenamePlanningError.duplicateSourceID }
        guard Set(sources.map { Data($0.originalName.utf8) }).count == sources.count else {
            throw BatchRenamePlanningError.duplicateOriginalName
        }
        var parts: [RenameNameParts] = []
        for source in sources {
            do { parts.append(try RenameNamePolicy.split(source.originalName, kind: source.kind)) }
            catch let error as RenameNameError {
                throw BatchRenamePlanningError.invalidOriginalName(rowID: source.id, reason: error)
            }
        }
        self.id = id; self.sources = sources; self.parts = parts
    }

    public static func == (lhs: Self, rhs: Self) -> Bool { lhs.id == rhs.id && lhs.sources == rhs.sources }
}

public enum BatchRenameOrder: String, Equatable, Sendable { case ascending, descending }
public enum BatchRenameCaseSensitivity: String, Equatable, Sendable { case unknown, sensitive, insensitive }

/// Text stays attached to an explicit row order. Only a confirmed reassignment
/// should call confirmingReassignment; retaining this value implements Cancel.
public struct BatchRenameNameList: Equatable, Sendable {
    public static let maximumBytes = 1_048_576
    public let text: String
    public let rowIDs: [UUID]
    public let bodies: [String]

    public init(text: String, rowIDs: [UUID]) throws {
        guard text.utf8.count <= Self.maximumBytes else { throw BatchRenamePlanningError.nameListTooLarge }
        guard (1...1_000).contains(rowIDs.count), Set(rowIDs).count == rowIDs.count else {
            throw BatchRenamePlanningError.invalidNameListBinding
        }
        var normalized = text.replacingOccurrences(of: "\r\n", with: "\n").replacingOccurrences(of: "\r", with: "\n")
        if normalized.hasSuffix("\n") { normalized.removeLast() }
        // Count before splitting: a bounded 1 MiB paste can still contain a
        // million empty lines, but only at most 1,000 row strings are needed.
        let lineCount = normalized.utf8.reduce(1) { $1 == 0x0A ? $0 + 1 : $0 }
        guard lineCount == rowIDs.count else {
            throw BatchRenamePlanningError.nameListLineCount(expected: rowIDs.count, actual: lineCount)
        }
        let bodies = normalized.components(separatedBy: "\n")
        self.text = text; self.rowIDs = rowIDs; self.bodies = bodies
    }

    public func confirmingReassignment(to rowIDs: [UUID]) throws -> Self {
        guard Set(rowIDs) == Set(self.rowIDs), rowIDs.count == self.rowIDs.count else {
            throw BatchRenamePlanningError.invalidNameListBinding
        }
        return try Self(text: text, rowIDs: rowIDs)
    }

    public static func == (lhs: Self, rhs: Self) -> Bool {
        lhs.rowIDs == rhs.rowIDs && lhs.text.utf8.elementsEqual(rhs.text.utf8)
    }
}

public enum BatchRenameMode: Equatable, Sendable {
    case rules([BatchRenameRule])
    case nameList(BatchRenameNameList)
}

/// Exact, immutable inputs bind target observations to one preview. No hash,
/// clock or random value is generated by the planner.
public struct BatchRenamePlanReference: Equatable, Sendable {
    public let batch: BatchRenameBatch
    public let revision: UInt64
    public let mode: BatchRenameMode
    public let order: BatchRenameOrder
    public let caseSensitivity: BatchRenameCaseSensitivity
    public let nativeNameByteLimit: Int?
}

public enum BatchRenameRowState: String, Equatable, Sendable {
    case checking, changed, unchanged, invalid, conflict
}

public enum BatchRenameRowIssue: Equatable, Sendable {
    case name(RenameNameError)
    case rule(BatchRenameRuleError)
    case blankNameListLine
    case duplicateTarget
    case occupiedTarget
    case originalTargetMissing
    case targetCheckFailed
}

public struct BatchRenameRow: Sendable {
    public let source: BatchRenameSource
    public let capturedOrdinal: Int
    public let proposedName: String?
    public let state: BatchRenameRowState
    public let issue: BatchRenameRowIssue?
    public let dependencyID: UUID?

    public var changesName: Bool {
        proposedName.map { !$0.utf8.elementsEqual(source.originalName.utf8) } ?? false
    }

    fileprivate func with(state: BatchRenameRowState, issue: BatchRenameRowIssue? = nil,
                          dependencyID: UUID? = nil) -> Self {
        .init(source: source, capturedOrdinal: capturedOrdinal, proposedName: proposedName,
              state: state, issue: issue, dependencyID: dependencyID)
    }
}

public struct BatchRenameCounts: Equatable, Sendable {
    public let changed: Int
    public let unchanged: Int
    public let checking: Int
    public let invalid: Int
    public let conflicts: Int
    public var errors: Int { invalid + conflicts }
}

public struct BatchRenamePreview: Sendable {
    public let reference: BatchRenamePlanReference
    public let rows: [BatchRenameRow]

    public var counts: BatchRenameCounts {
        .init(changed: rows.filter { $0.state == .changed }.count,
              unchanged: rows.filter { $0.state == .unchanged }.count,
              checking: rows.filter { $0.state == .checking }.count,
              invalid: rows.filter { $0.state == .invalid }.count,
              conflicts: rows.filter { $0.state == .conflict }.count)
    }
    /// A proposed-name count, never a count of filesystem mutations.
    public var proposedChangeCount: Int { rows.filter(\.changesName).count }
    public var canFreeze: Bool {
        reference.caseSensitivity != .unknown && counts.errors == 0 && counts.checking == 0 && counts.changed > 0
    }
}

public enum BatchRenameTargetState: Equatable, Sendable {
    case pending
    case absent
    /// The exact entry is a captured source (not merely another hard link with
    /// the same inode). The native observer must verify that distinction.
    case occupiedBySource(UUID)
    case occupiedExternally
    case failed
}

public struct BatchRenameTargetObservation: Sendable {
    public let rowID: UUID
    public let targetName: String
    public let state: BatchRenameTargetState

    public init(rowID: UUID, targetName: String, state: BatchRenameTargetState) {
        self.rowID = rowID; self.targetName = targetName; self.state = state
    }
}

/// One complete observation revision: omitted rows stay checking. Observations
/// never accumulate across revisions or imply that a missing key means absent.
public struct BatchRenameTargetSnapshot: Sendable {
    public let reference: BatchRenamePlanReference
    public let observations: [BatchRenameTargetObservation]

    public init(preview: BatchRenamePreview, observations: [BatchRenameTargetObservation]) {
        reference = preview.reference; self.observations = observations
    }
}

/// A frozen naming proposal only. P2 must revalidate native identities, authority
/// and exact targets at submission and every forward step before performing I/O.
public struct BatchRenamePlan: Sendable {
    public let reference: BatchRenamePlanReference
    public let rows: [BatchRenameRow]
    public var changedCount: Int { rows.filter(\.changesName).count }
    public var unchangedCount: Int { rows.count - changedCount }
}

public enum BatchRenamePlanner {
    public static func orderedRowIDs(in batch: BatchRenameBatch, order: BatchRenameOrder = .ascending) -> [UUID] {
        orderedIndices(in: batch, order: order).map { batch.sources[$0].id }
    }

    public static func preview(batch: BatchRenameBatch, revision: UInt64, mode: BatchRenameMode,
                               order: BatchRenameOrder = .ascending,
                               caseSensitivity: BatchRenameCaseSensitivity = .unknown,
                               nativeNameByteLimit: Int? = nil) throws -> BatchRenamePreview {
        let indices = orderedIndices(in: batch, order: order)
        let sensitive = caseSensitivity != .insensitive
        switch mode {
        case .rules(let rules): try BatchRenameRuleEngine.validate(rules, rowCount: batch.sources.count)
        case .nameList(let list):
            guard list.rowIDs == indices.map({ batch.sources[$0].id }) else {
                throw BatchRenamePlanningError.nameListOrderNeedsConfirmation
            }
        }
        var rows: [BatchRenameRow] = []
        for (ordinal, captured) in indices.enumerated() {
            let source = batch.sources[captured]
            let parts = batch.parts[captured]
            if case .nameList(let list) = mode,
               list.bodies[ordinal].unicodeScalars.allSatisfy({ $0.properties.isWhitespace }) {
                rows.append(.init(source: source, capturedOrdinal: captured, proposedName: nil,
                                  state: .invalid, issue: .blankNameListLine, dependencyID: nil))
                continue
            }
            let name: String?, issue: BatchRenameRowIssue?
            do {
                let body: String
                switch mode {
                case .rules(let rules):
                    body = try BatchRenameRuleEngine.apply(rules, to: parts.body, sortedOrdinal: ordinal,
                                                          rowCount: batch.sources.count)
                case .nameList(let list): body = list.bodies[ordinal]
                }
                name = try RenameNamePolicy.output(body: body, parts: parts, nativeNameByteLimit: nativeNameByteLimit)
                issue = nil
            } catch let error as RenameNameError { name = nil; issue = .name(error) }
              catch let error as BatchRenameRuleError { name = nil; issue = .rule(error) }
            rows.append(.init(source: source, capturedOrdinal: captured, proposedName: name,
                              state: issue == nil ? .checking : .invalid, issue: issue, dependencyID: nil))
        }
        var groups: [Data: [Int]] = [:]
        for (index, row) in rows.enumerated() {
            if let name = row.proposedName {
                groups[RenameNamePolicy.namespaceKey(name, caseSensitive: sensitive), default: []].append(index)
            }
        }
        for indices in groups.values where indices.count > 1 {
            for index in indices { rows[index] = rows[index].with(state: .conflict, issue: .duplicateTarget) }
        }
        return .init(reference: .init(batch: batch, revision: revision, mode: mode, order: order,
                                      caseSensitivity: caseSensitivity, nativeNameByteLimit: nativeNameByteLimit), rows: rows)
    }

    public static func checkingTargets(of preview: BatchRenamePreview,
                                       using snapshot: BatchRenameTargetSnapshot) throws -> BatchRenamePreview {
        guard preview.reference == snapshot.reference else { throw BatchRenamePlanningError.staleTargetSnapshot }
        let reference = preview.reference
        // Always start with fresh pure results: a later pending/error observation
        // must revoke an earlier successful check, even within the same revision.
        let base = try self.preview(batch: reference.batch, revision: reference.revision, mode: reference.mode,
                                    order: reference.order, caseSensitivity: reference.caseSensitivity,
                                    nativeNameByteLimit: reference.nativeNameByteLimit)
        let byID = Dictionary(uniqueKeysWithValues: base.rows.map { ($0.source.id, $0) })
        var observations: [UUID: BatchRenameTargetState] = [:]
        for observation in snapshot.observations {
            guard observations[observation.rowID] == nil, let row = byID[observation.rowID],
                  let name = row.proposedName, name.utf8.elementsEqual(observation.targetName.utf8) else {
                throw BatchRenamePlanningError.invalidTargetObservation
            }
            if case .occupiedBySource(let id) = observation.state {
                guard let occupant = byID[id],
                      RenameNamePolicy.namespaceKey(occupant.source.originalName, caseSensitive: reference.caseSensitivity != .insensitive)
                        == RenameNamePolicy.namespaceKey(name, caseSensitive: reference.caseSensitivity != .insensitive) else {
                    throw BatchRenamePlanningError.invalidTargetObservation
                }
            }
            observations[observation.rowID] = observation.state
        }
        let rows = base.rows.map { row -> BatchRenameRow in
            guard row.issue == nil, let observation = observations[row.source.id] else { return row }
            let readyState: BatchRenameRowState = row.changesName ? .changed : .unchanged
            switch observation {
            case .pending: return row
            case .failed: return row.with(state: .invalid, issue: .targetCheckFailed)
            case .occupiedExternally: return row.with(state: .conflict, issue: .occupiedTarget)
            case .absent:
                guard row.changesName else { return row.with(state: .invalid, issue: .originalTargetMissing) }
                return reference.caseSensitivity == .unknown ? row : row.with(state: readyState)
            case .occupiedBySource(let id):
                guard id == row.source.id || byID[id]?.changesName == true else {
                    return row.with(state: .conflict, issue: .occupiedTarget)
                }
                return reference.caseSensitivity == .unknown ? row : row.with(state: readyState,
                    dependencyID: id == row.source.id ? nil : id)
            }
        }
        return .init(reference: reference, rows: rows)
    }

    public static func freeze(_ preview: BatchRenamePreview) throws -> BatchRenamePlan {
        guard preview.reference.caseSensitivity != .unknown else { throw BatchRenamePlanningError.unknownCaseSensitivity }
        guard preview.counts.errors == 0 && preview.counts.checking == 0 else {
            throw BatchRenamePlanningError.previewNotReady
        }
        guard preview.counts.changed > 0 else { throw BatchRenamePlanningError.noChanges }
        return .init(reference: preview.reference, rows: preview.rows)
    }

    private static func orderedIndices(in batch: BatchRenameBatch, order: BatchRenameOrder) -> [Int] {
        let ascending = batch.sources.indices.sorted { lhs, rhs in
            let result = RenameNamePolicy.compareOriginalNames(batch.sources[lhs].originalName, batch.sources[rhs].originalName)
            return result == .orderedSame ? lhs < rhs : result == .orderedAscending
        }
        return order == .ascending ? ascending : Array(ascending.reversed())
    }
}
